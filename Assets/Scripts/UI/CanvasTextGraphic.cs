#nullable enable
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;

namespace PlantsVsZombies.UI
{
    /// <summary>Renders native Canvas text with explicit pixel transforms and group clipping.</summary>
    public sealed class CanvasTextGraphic : Text
    {
        /// <summary>The native text triangles reused between mesh rebuilds.</summary>
        private readonly List<UIVertex> _source = new List<UIVertex>();
        /// <summary>The transformed triangle reused by the clipping operation.</summary>
        private readonly UIVertex[] _triangle = new UIVertex[3];
        /// <summary>The reusable clipping buffers for native text triangles.</summary>
        private readonly CanvasMeshClipper _clipper = new CanvasMeshClipper();
        /// <summary>The text origin before applying the inherited pixel transform.</summary>
        private Vector2 _origin;
        /// <summary>The transform from text-local coordinates to top-left screen pixels.</summary>
        private Matrix4x4 _matrix;
        /// <summary>The clipping rectangle in top-left screen pixels.</summary>
        private Rect _clip;

        /// <summary>Configures native text layout and the transform inherited from its view.</summary>
        /// <param name="destination">The original text bounds, including style padding.</param>
        /// <param name="value">The visible text.</param>
        /// <param name="style">The text layout settings supplied by the view.</param>
        /// <param name="matrix">The inherited transform to screen pixels.</param>
        /// <param name="tint">The final text color and opacity.</param>
        /// <param name="clip">The current group clipping rectangle.</param>
        internal void Configure(Rect destination, string value, GUIStyle style, Matrix4x4 matrix, Color tint, Rect clip)
        {
            var padding = style.padding;
            var origin = new Vector2(destination.x + padding.left, destination.y + padding.top);
            var effectiveClip = style.clipping == TextClipping.Clip ? CanvasUI.Intersect(clip, CanvasUI.TransformBounds(destination, matrix)) : clip;
            var geometryChanged = !_origin.Equals(origin) || !_matrix.Equals(matrix) || !_clip.Equals(effectiveClip);
            _origin = origin;
            var size = new Vector2(Mathf.Max(0f, destination.width - padding.horizontal), Mathf.Max(0f, destination.height - padding.vertical));
            if (rectTransform.sizeDelta != size)
            {
                rectTransform.sizeDelta = size;
            }
            font = style.font != null ? style.font : CanvasUI.DefaultFont;
            fontSize = Mathf.Max(1, style.fontSize);
            fontStyle = style.fontStyle;
            alignment = style.alignment;
            supportRichText = style.richText;
            horizontalOverflow = style.wordWrap ? HorizontalWrapMode.Wrap : HorizontalWrapMode.Overflow;
            verticalOverflow = VerticalWrapMode.Overflow;
            text = value;
            color = tint;
            raycastTarget = false;
            _matrix = matrix;
            _clip = effectiveClip;

            if (geometryChanged)
            {
                SetVerticesDirty();
            }
        }

        /// <summary>Transforms and clips the triangles generated by Unity's native text layout.</summary>
        /// <param name="helper">The mesh receiving the final visible text.</param>
        protected override void OnPopulateMesh(VertexHelper helper)
        {
            base.OnPopulateMesh(helper);
            _source.Clear();
            helper.GetUIVertexStream(_source);
            helper.Clear();
            for (var index = 0; index + 2 < _source.Count; index += 3)
            {
                for (var corner = 0; corner < 3; corner++)
                {
                    var vertex = _source[index + corner];
                    var position = _matrix.MultiplyPoint3x4(new Vector3(_origin.x + vertex.position.x, _origin.y - vertex.position.y));
                    vertex.position = new Vector3(position.x, -position.y);
                    _triangle[corner] = vertex;
                }

                _clipper.AddPolygon(helper, _triangle, 3, _clip);
            }
        }
    }
}
