param(
    [string]$InputDirectory = (Join-Path $PSScriptRoot '../../analysis/ida/balance'),
    [switch]$Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$expectedExeSha256 = 'E1511201EC2AE9A7E30259F04BC2EC7272BADB2574A2E9B405D0E916AE5C082C'
$outputPath = Join-Path $PSScriptRoot '../Assets/Scripts/VerifiedData/VerifiedDataTables.generated.cs'
$utf8 = [System.Text.UTF8Encoding]::new($false)
$invariant = [System.Globalization.CultureInfo]::InvariantCulture

function Read-Table([string]$name) {
    $path = Join-Path $InputDirectory ($name + '.json')
    $table = [IO.File]::ReadAllText($path, $utf8) | ConvertFrom-Json
    if ($table.source.all_exported_table_bytes_match_exe -isnot [bool] -or
        $table.source.all_exported_table_bytes_match_exe -ne $true -or
        $table.source.exe_sha256 -cne $expectedExeSha256) {
        throw "Unexpected or unverified EXE source in $path"
    }
    return $table
}

function Get-Integer($value, [string]$description) {
    if (($value -isnot [int] -and $value -isnot [long]) -or
        $value -lt [int]::MinValue -or $value -gt [int]::MaxValue) {
        throw "Expected a 32-bit integer for $description"
    }
    return [int]$value
}

function Format-Integer($value, [string]$description) {
    $number = Get-Integer $value $description
    return $number.ToString($invariant)
}

function Format-String($value, [string]$description) {
    if ($value -isnot [string]) { throw "Expected a string for $description" }
    $result = [System.Text.StringBuilder]::new()
    [void]$result.Append('"')
    foreach ($character in $value.ToCharArray()) {
        $code = [int]$character
        if ($code -eq 34) { [void]$result.Append('\"') }
        elseif ($code -eq 92) { [void]$result.Append('\\') }
        elseif ($code -lt 32 -or $code -gt 126) { [void]$result.AppendFormat($invariant, '\u{0:X4}', $code) }
        else { [void]$result.Append($character) }
    }
    [void]$result.Append('"')
    return $result.ToString()
}

function Assert-Ids([object[]]$rows, [string]$property, [int]$first, [int]$count, [string]$description) {
    if ($rows.Count -ne $count) { throw "Expected $count $description rows; got $($rows.Count)" }
    for ($i = 0; $i -lt $count; $i++) {
        $id = Get-Integer $rows[$i].$property "$description row ID"
        if ($id -ne ($first + $i)) { throw "Unexpected $description row ID $id at index $i" }
    }
}

function Assert-AnimationReference($row, [object[]]$animations, [string]$description) {
    $id = Get-Integer $row.reanimation_id.value "$description animation ID"
    if ($id -lt 0 -or $id -ge $animations.Count -or $row.reanimation_path -cne $animations[$id].path) {
        throw "Invalid animation reference for $description"
    }
}

$plants = Read-Table 'plants_full'
$zombies = Read-Table 'zombies_full'
$adventure = Read-Table 'adventure_levels_full'
$modes = Read-Table 'challenge_modes_full'
$animations = Read-Table 'reanimations_full'

Assert-Ids $plants.rows 'id' 0 53 'plant'
Assert-Ids $zombies.rows 'id' 0 34 'zombie'
Assert-Ids $adventure.levels 'level_index_1_based' 1 50 'adventure level'
Assert-Ids $adventure.zombie_row_headers 'zombie_id_index' 0 34 'adventure zombie header'
Assert-Ids $modes.rows 'id' 1 72 'challenge mode'
Assert-Ids $animations.rows 'id' 0 144 'reanimation'
if ($plants.table.row_count -ne 53 -or $zombies.table.row_count -ne 34 -or
    $adventure.table.level_row_count -ne 50 -or $adventure.table.zombie_type_column_count -ne 34 -or
    $adventure.table.flag_cell_count -ne 1700 -or $modes.table.row_count -ne 72 -or
    $animations.table.row_count -ne 144) {
    throw 'Unexpected source table dimensions'
}
foreach ($row in $plants.rows) { Assert-AnimationReference $row $animations.rows "plant $($row.id)" }
foreach ($row in $zombies.rows) { Assert-AnimationReference $row $animations.rows "zombie $($row.id)" }
foreach ($level in $adventure.levels) {
    Assert-Ids $level.zombie_flag_cells 'zombie_id' 0 34 "level $($level.level_index_1_based) zombie flag"
}

$builder = [System.Text.StringBuilder]::new()
function Add-Line([string]$line = '') { [void]$builder.Append($line).Append("`r`n") }
function Start-Table([string]$type, [string]$field) {
    Add-Line "        /// <summary>Contains the verified $field records.</summary>"
    Add-Line "        internal static readonly ReadOnlyCollection<$type> s_$field ="
    Add-Line "            Array.AsReadOnly(new ${type}[]"
    Add-Line '            {'
}
function End-Table {
    Add-Line '            });'
    Add-Line
}

Add-Line '// <auto-generated />'
Add-Line '// Generated from verified IDA JSON. Do not edit; see Tools/GenerateVerifiedData.ps1.'
Add-Line '// Static table definitions only; these do not implement gameplay or complete level scripts.'
Add-Line '#nullable enable'
Add-Line 'using System;'
Add-Line 'using System.Collections.ObjectModel;'
Add-Line
Add-Line 'namespace PlantsVsZombies.VerifiedData'
Add-Line '{'
Add-Line '    /// <summary>Contains immutable data exported from the verified original game tables.</summary>'
Add-Line '    internal static class VerifiedDataTables'
Add-Line '    {'
Add-Line '        /// <summary>Identifies the verified source executable.</summary>'
Add-Line ('        internal const string SourceExeSha256 = ' + (Format-String $expectedExeSha256 'EXE SHA-256') + ';')
Add-Line

Start-Table 'PlantDefinition' 'plants'
foreach ($row in $plants.rows) {
    $fields = @(
        (Format-Integer $row.id 'plant ID')
        (Format-String $row.internal_name 'plant name')
        (Format-Integer $row.sun_cost.value 'plant cost')
        (Format-Integer $row.recharge_threshold_raw.value 'plant recharge threshold')
        (Format-Integer $row.reanimation_id.value 'plant animation ID')
        (Format-Integer $row.action_dispatch_code_raw.value 'plant action code')
        (Format-Integer $row.action_period_raw.value 'plant action period')
        (Format-Integer $row.unidentified_0x04.value 'plant unidentified 0x04')
        (Format-Integer $row.unidentified_0x0c.value 'plant unidentified 0x0c')
    )
    Add-Line ('                new PlantDefinition(' + ($fields -join ', ') + '),')
}
End-Table

Start-Table 'ZombieDefinition' 'zombies'
foreach ($row in $zombies.rows) {
    $fields = @(
        (Format-Integer $row.id 'zombie ID')
        (Format-String $row.internal_name 'zombie name')
        (Format-Integer $row.reanimation_id.value 'zombie animation ID')
        (Format-Integer $row.wave_budget_cost_raw.value 'zombie budget cost')
        (Format-Integer $row.base_level_gate_raw.value 'zombie level gate')
        (Format-Integer $row.base_wave_gate_raw.value 'zombie wave gate')
        (Format-Integer $row.base_selection_weight_raw.value 'zombie selection weight')
    )
    Add-Line ('                new ZombieDefinition(' + ($fields -join ', ') + '),')
}
End-Table

Start-Table 'AdventureLevelDefinition' 'adventureLevels'
foreach ($row in $adventure.levels) {
    $id = Format-Integer $row.level_index_1_based 'adventure level ID'
    $waves = Format-Integer $row.base_wave_count.value 'adventure base wave count'
    $flags = @($row.zombie_flag_cells | ForEach-Object { Format-Integer $_.flag 'adventure zombie flag' })
    Add-Line ("                new AdventureLevelDefinition($id, $waves, new int[] { " + ($flags -join ', ') + ' }),')
}
End-Table

Start-Table 'AdventureZombieRowHeader' 'adventureZombieRowHeaders'
foreach ($row in $adventure.zombie_row_headers) {
    $id = Format-Integer $row.zombie_id_index 'adventure zombie header ID'
    $header = Format-Integer $row.stored_header 'adventure zombie stored header'
    Add-Line "                new AdventureZombieRowHeader($id, $header),"
}
End-Table

Start-Table 'ChallengeModeDefinition' 'challengeModes'
foreach ($row in $modes.rows) {
    $fields = @(
        (Format-Integer $row.id 'mode ID')
        (Format-String $row.localization_key 'mode localization key')
        (Format-Integer $row.ui_category_index.value 'mode UI category')
        (Format-Integer $row.ui_grid_row.value 'mode UI row')
        (Format-Integer $row.ui_grid_column.value 'mode UI column')
        (Format-Integer $row.unidentified_0x04.value 'mode unidentified 0x04')
    )
    Add-Line ('                new ChallengeModeDefinition(' + ($fields -join ', ') + '),')
}
End-Table

Start-Table 'ReanimationDefinition' 'reanimations'
foreach ($row in $animations.rows) {
    $fields = @(
        (Format-Integer $row.id 'reanimation ID')
        (Format-String $row.path 'reanimation path')
        (Format-Integer $row.unknown_0x08.value 'reanimation unknown 0x08')
    )
    Add-Line ('                new ReanimationDefinition(' + ($fields -join ', ') + '),')
}
End-Table
Add-Line '    }'
Add-Line '}'

$expectedBytes = $utf8.GetBytes($builder.ToString())
if ($Check) {
    if (-not [IO.File]::Exists($outputPath) -or
        [Convert]::ToBase64String([IO.File]::ReadAllBytes($outputPath)) -cne [Convert]::ToBase64String($expectedBytes)) {
        throw "Generated data is missing or out of date: $outputPath"
    }
    Write-Host 'Verified generated data matches the JSON exports.'
}
else {
    [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($outputPath))
    [IO.File]::WriteAllBytes($outputPath, $expectedBytes)
    Write-Host "Generated $outputPath"
}
